// Helper function to create sample documents
const createSampleDocuments = (count: number, baseDate: Date): MemberDocument[] => {
  const docs: MemberDocument[] = [];
  const docTypes = ['pdf', 'image', 'document'];
  const docNames = [
    'Medical Report',
    'ID Card',
    'Health Certificate',
    'Insurance Card',
    'Emergency Contact Form',
    'Medical History',
    'Prescription',
    'Lab Results'
  ];
  
  for (let i = 0; i < count; i++) {
    docs.push({
      id: `doc-${Date.now()}-${i}`,
      name: docNames[i % docNames.length] + (i > 0 ? ` ${i + 1}` : '') + (docTypes[i % docTypes.length] === 'pdf' ? '.pdf' : docTypes[i % docTypes.length] === 'image' ? '.jpg' : '.doc'),
      type: docTypes[i % docTypes.length],
      url: `https://example.com/documents/${docNames[i % docNames.length].toLowerCase().replace(/\s+/g, '-')}.${docTypes[i % docTypes.length] === 'pdf' ? 'pdf' : docTypes[i % docTypes.length] === 'image' ? 'jpg' : 'doc'}`,
      uploadedAt: subDays(baseDate, Math.floor(Math.random() * 30)).toISOString(),
    });
  }
  return docs;
};

